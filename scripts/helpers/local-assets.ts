import fs from "node:fs";
import path from "node:path";
import {createHash} from "node:crypto";
import {SOLCORD_CATALOG_DETAIL_SHA256} from "../../src/common/solcord/addon-trust.generated";

export function assertSolcordCatalogAsset(file: string): void {
    const stat = fs.lstatSync(file);
    if (!stat.isFile() || stat.isSymbolicLink() || stat.size <= 0 || stat.size > 2 * 1024 * 1024
        || createHash("sha256").update(fs.readFileSync(file)).digest("hex") !== SOLCORD_CATALOG_DETAIL_SHA256) {
        throw new Error("Local catalog digest does not match the pinned renderer asset. Restore the canonical generated bytes before building or packaging.");
    }
}

export function solcordLocalAssets(root: string): Array<{source: string; target: string;}> {
    const catalog = path.join(root, "assets/catalog/solcord-browsing.generated.json");
    assertSolcordCatalogAsset(catalog);
    const assets = [{source: catalog, target: "catalog/index.json"},
        {source: path.join(root, "src/betterdiscord/styles/fonts/HankenGrotesk-variable.ttf"), target: "fonts/HankenGrotesk-variable.ttf"},
        {source: path.join(root, "node_modules/monaco-editor/LICENSE"), target: "editor/monaco/LICENSE"}];
    const sourceRoot = path.join(root, "node_modules/monaco-editor/min/vs");
    const walk = (directory: string) => {
        for (const entry of fs.readdirSync(directory, {withFileTypes: true}).sort((a, b) => a.name.localeCompare(b.name, "en"))) {
            const source = path.join(directory, entry.name);
            if (entry.isSymbolicLink()) throw new Error("Local editor assets cannot contain links.");
            if (entry.isDirectory()) walk(source);
            else if (entry.isFile()) assets.push({source, target: `editor/monaco/vs/${path.relative(sourceRoot, source).replaceAll("\\", "/")}`});
        }
    };
    walk(sourceRoot);
    return assets;
}

export function stageSolcordLocalAssets(root: string): void {
    for (const {source, target} of solcordLocalAssets(root)) {
        const destination = path.join(root, "dist", target);
        fs.mkdirSync(path.dirname(destination), {recursive: true});
        fs.copyFileSync(source, destination);
        if (target === "catalog/index.json") assertSolcordCatalogAsset(destination);
    }
}
